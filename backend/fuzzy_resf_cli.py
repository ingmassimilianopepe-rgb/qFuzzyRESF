#!/usr/bin/env python3

from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

if __name__ == "__main__":
    from runtime_bootstrap import ensure_runtime
    ensure_runtime(__file__)

from bim_reconstruction import write_csv, write_model_json
from architectural_graph_v5_1 import reconstruct_bim as reconstruct_v51
from building_shell_v6 import reconstruct_bim as reconstruct_v6
from building_shell_v6_1 import reconstruct_bim as reconstruct_v61
from building_shell_v6_2 import reconstruct_bim as reconstruct_v62
from building_shell_v6_3 import reconstruct_bim as reconstruct_v63
from building_shell_v6_4 import reconstruct_bim as reconstruct_v64
from building_shell_v6_5 import reconstruct_bim as reconstruct_v65
import building_shell_v7 as _v7_helpers
from building_shell_v7 import reconstruct_bim as reconstruct_v70
import building_shell_v7_1 as _v71
_v71.v7 = _v7_helpers
reconstruct_v71 = _v71.reconstruct_bim
from building_shell_v7_2 import reconstruct_bim as reconstruct_v72
from ifc_bim_export_v7 import write_bim_ifc


def _write_summary(summary: dict, path: Path) -> None:
    path.write_text(json.dumps(summary, indent=2), encoding="utf-8")


def _select_reconstructor(request: dict):
    preset = str(request.get("preset", ""))
    version = str(request.get("version", ""))
    if "5.1" in preset or version.startswith("5.1"):
        return reconstruct_v51
    if "6.0" in preset or version.startswith("6.0"):
        return reconstruct_v6
    if "6.1" in preset or version.startswith("6.1"):
        return reconstruct_v61
    if "6.2" in preset or version.startswith("6.2"):
        return reconstruct_v62
    if "6.3" in preset or version.startswith("6.3"):
        return reconstruct_v63
    if "6.4" in preset or version.startswith("6.4"):
        return reconstruct_v64
    if "6.5" in preset or version.startswith("6.5"):
        return reconstruct_v65
    if "7.0" in preset or version.startswith("7.0"):
        return reconstruct_v70
    if "7.1" in preset or version.startswith("7.1"):
        return reconstruct_v71
    if "7.2" in preset or version.startswith("7.2"):
        return reconstruct_v72
    return reconstruct_v72


def main() -> int:
    parser = argparse.ArgumentParser(description="qFuzzyRESF semantic-topological BIM backend")
    parser.add_argument("--request", required=True, help="Path to the JSON request generated by the CloudCompare plugin")
    args = parser.parse_args()

    request_path = Path(args.request)
    request = json.loads(request_path.read_text(encoding="utf-8"))
    if str(request.get("version", "")).startswith("8.") or "8.0" in str(request.get("preset", "")):
        from semantic_resf_cli import main as stepwise_main
        return stepwise_main(["--request", str(request_path)])
    output_dir = Path(request["output"])
    output_dir.mkdir(parents=True, exist_ok=True)
    result_path = output_dir / "result.json"

    try:
        model = _select_reconstructor(request)(request)
        if not model.walls:
            raise RuntimeError("No accepted physical BIM wall instances were reconstructed; IFC export aborted")

        walls_path = output_dir / "walls.csv"
        uncertain_walls_path = output_dir / "uncertain_walls.csv"
        openings_path = output_dir / "openings.csv"
        spaces_path = output_dir / "spaces.csv"
        slabs_path = output_dir / "slabs.csv"
        roofs_path = output_dir / "roofs.csv"
        columns_path = output_dir / "columns.csv"
        stairs_path = output_dir / "stairs.csv"
        candidates_path = output_dir / "resf_candidates.csv"
        model_path = output_dir / "bim_model.json"
        decisions_path = output_dir / "object_decisions.json"
        abacus_path = output_dir / "object_abacus.json"
        standards_path = output_dir / "standards_alignment.json"
        restoration_path = output_dir / "restoration_policy.json"
        ifc_path = output_dir / "fuzzy_resf.ifc"

        wall_fields = [
            "id", "storey_id", "x1", "y1", "x2", "y2", "z0", "z1", "thickness",
            "theta_deg", "confidence", "support", "continuity", "source", "state",
            "resf_A", "resf_EH", "resf_EV", "resf_C", "resf_N", "resf_O", "geometric_feedback",
        ]
        write_csv(model.walls, walls_path, wall_fields)
        uncertain_walls = list(getattr(model, "uncertain_wall_hypotheses", []))
        write_csv(uncertain_walls, uncertain_walls_path, wall_fields)
        write_csv(model.openings, openings_path,
                  ["id", "wall_id", "storey_id", "kind", "offset", "width", "sill", "height", "confidence", "source"])
        write_csv(model.spaces, spaces_path,
                  ["id", "storey_id", "name", "polygon", "z0", "z1", "area", "confidence"])
        write_csv(model.slabs, slabs_path,
                  ["id", "storey_id", "kind", "polygon", "z", "thickness", "confidence"])
        roofs = list(getattr(model, "roofs", []))
        write_csv(roofs, roofs_path,
                  ["id", "storey_id", "vertices", "thickness", "confidence", "source"])
        columns = list(getattr(model, "columns", []))
        write_csv(columns, columns_path,
                  ["id", "storey_id", "x", "y", "z0", "z1", "width", "depth", "theta_deg", "confidence", "source"])
        stairs = list(getattr(model, "stairs", []))
        write_csv(stairs, stairs_path,
                  ["id", "storey_id", "x", "y", "z", "width", "tread_depth", "riser_height", "step_count", "theta_deg", "confidence", "source"])
        write_csv(model.candidates, candidates_path, [
            "id", "storey_id", "theta_deg", "d", "t0", "t1", "z0", "z1",
            "A_star", "E_H", "E_V", "C", "N", "O", "rho", "semantic_wall",
            "T_F", "T_C", "T_W", "T_B", "T_R", "T_CP", "G", "confidence", "state",
        ])

        write_model_json(model, model_path)
        payload = json.loads(model_path.read_text(encoding="utf-8"))
        from dataclasses import asdict
        if roofs:
            payload["roofs"] = [asdict(x) for x in roofs]
        if columns:
            payload["columns"] = [asdict(x) for x in columns]
        if stairs:
            payload["stairs"] = [asdict(x) for x in stairs]
        if uncertain_walls:
            payload["uncertain_wall_hypotheses"] = [asdict(x) for x in uncertain_walls]
        if hasattr(model, "object_decisions"):
            payload["object_decisions"] = model.object_decisions
            decisions_path.write_text(json.dumps(model.object_decisions, indent=2), encoding="utf-8")
        if hasattr(model, "object_abacus"):
            payload["object_abacus"] = model.object_abacus
            abacus_path.write_text(json.dumps(model.object_abacus, indent=2), encoding="utf-8")
        if hasattr(model, "standards_alignment"):
            payload["standards_alignment"] = model.standards_alignment
            standards_path.write_text(json.dumps(model.standards_alignment, indent=2), encoding="utf-8")
        if hasattr(model, "restoration_policy"):
            payload["restoration_policy"] = model.restoration_policy
            restoration_path.write_text(json.dumps(model.restoration_policy, indent=2), encoding="utf-8")
        model_path.write_text(json.dumps(payload, indent=2), encoding="utf-8")

        if request.get("export_ifc", True):
            write_bim_ifc(model, ifc_path)
            if not ifc_path.exists() or ifc_path.stat().st_size < 1024:
                raise RuntimeError("IFC exporter produced an invalid or unexpectedly small file")
            text = ifc_path.read_text(encoding="utf-8", errors="ignore").upper()
            if "IFCWALLSTANDARDCASE" not in text or "IFCBUILDINGSTOREY" not in text:
                raise RuntimeError("IFC validation failed: semantic wall/storey entities are missing")
            if any(o.kind == "Door" for o in model.openings) and "IFCDOOR" not in text:
                raise RuntimeError("IFC validation failed: detected doors were not exported as IfcDoor")
            if any(o.kind == "Window" for o in model.openings) and "IFCWINDOW" not in text:
                raise RuntimeError("IFC validation failed: detected windows were not exported as IfcWindow")
            if model.spaces and "IFCSPACE" not in text:
                raise RuntimeError("IFC validation failed: reconstructed spaces were not exported as IfcSpace")
            if roofs and ".ROOF." not in text:
                raise RuntimeError("IFC validation failed: reconstructed roof facets are missing from the IFC")
            if columns and "IFCCOLUMN" not in text:
                raise RuntimeError("IFC validation failed: reconstructed structural columns are missing from the IFC")
            if stairs and "IFCSTAIRFLIGHT" not in text:
                raise RuntimeError("IFC validation failed: reconstructed stairs are missing as IfcStairFlight")
            if hasattr(model, "standards_alignment") and "PSET_FUZZYRESF_V7_METHOD" not in text:
                raise RuntimeError("IFC validation failed: v7 method/standards metadata was not exported")

        summary = dict(model.summary)
        summary.update({
            "preset": request.get("preset", "Fuzzy-RESF-BIM 7.2 (Restored evidence graph)"),
            "walls_csv": str(walls_path),
            "uncertain_walls_csv": str(uncertain_walls_path),
            "openings_csv": str(openings_path),
            "spaces_csv": str(spaces_path), "slabs_csv": str(slabs_path), "roofs_csv": str(roofs_path),
            "columns_csv": str(columns_path), "stairs_csv": str(stairs_path),
            "resf_candidates_csv": str(candidates_path), "bim_model_json": str(model_path),
            "object_decisions_json": str(decisions_path) if decisions_path.exists() else None,
            "object_abacus_json": str(abacus_path) if abacus_path.exists() else None,
            "standards_alignment_json": str(standards_path) if standards_path.exists() else None,
            "restoration_policy_json": str(restoration_path) if restoration_path.exists() else None,
            "ifc": str(ifc_path) if request.get("export_ifc", True) else None,
        })
        _write_summary(summary, result_path)
        for warning in summary.get("warnings", []):
            print(f"WARNING: {warning}", file=sys.stderr)
        return 0
    except Exception as exc:
        error = {"status": "error", "method": "Fuzzy-RESF-BIM",
                 "version": "7.2-restored-evidence-graph",
                 "error": f"{type(exc).__name__}: {exc}"}
        _write_summary(error, result_path)
        print(error["error"], file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
