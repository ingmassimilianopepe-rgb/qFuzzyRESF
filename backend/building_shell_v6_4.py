"""Fuzzy-RESF-BIM v6.4: architectural-primitives reconstruction.

Targets residual defects visible on real historic-building scans:
- wall/roof zig-zag caused by raster/hull micro-vertices;
- incomplete room subdivision from nearly connected partitions;
- missing exterior stair flights under porches and entrances.

The RESF/fuzzy evidence stage is unchanged.  This module regularizes the physical object
layer after v6.3 and adds explicit scan-derived staircase detection.  No reference BIM is
read at runtime.
"""
from __future__ import annotations

from dataclasses import dataclass
import math
import numpy as np
from shapely.geometry import LineString, MultiPoint, Point, Polygon
from shapely.ops import unary_union

import bim_reconstruction as base
import architectural_graph_v5 as core
import building_shell_v6 as v6
import building_shell_v6_1 as v61
import building_shell_v6_3 as v63
from topology_completion import geometric_feedback, snap_wall_graph

RoofFacet = v6.RoofFacet


@dataclass
class StairFlight:
    id: int
    storey_id: int
    x: float
    y: float
    z: float
    width: float
    tread_depth: float
    riser_height: float
    step_count: int
    theta_deg: float
    confidence: float
    source: str = "repeated_horizontal_tread_sequence"


def _line_angle(a, b) -> float:
    d = np.asarray(b, dtype=float) - np.asarray(a, dtype=float)
    return float(math.degrees(math.atan2(d[1], d[0])) % 180.0)


def _remove_micro_corners(poly: Polygon, cell: float) -> Polygon:
    """Remove hull/raster micro-corners without forcing a global Manhattan model."""
    if poly is None or poly.geom_type != "Polygon":
        return poly
    pts = [np.asarray(p, dtype=float) for p in list(poly.exterior.coords)[:-1]]
    if len(pts) < 4:
        return poly
    changed = True
    min_short = max(0.34, 3.2 * cell)
    while changed and len(pts) > 4:
        changed = False
        for i in range(len(pts)):
            p0, p1, p2 = pts[i - 1], pts[i], pts[(i + 1) % len(pts)]
            l0 = float(np.linalg.norm(p1 - p0)); l1 = float(np.linalg.norm(p2 - p1))
            if l0 < 1e-8 or l1 < 1e-8:
                del pts[i]; changed = True; break
            da = v63._adiff(_line_angle(p0, p1), _line_angle(p1, p2))
            chord = LineString([p0, p2])
            deviation = float(chord.distance(Point(float(p1[0]), float(p1[1]))))
            # Collinear saw-tooth or tiny chamfer generated by rasterisation.
            if da <= 7.0 or (min(l0, l1) <= min_short and da <= 30.0 and deviation <= 0.18):
                del pts[i]; changed = True; break
    out = Polygon([[float(p[0]), float(p[1])] for p in pts])
    if not out.is_valid:
        out = out.buffer(0)
    if out.geom_type != "Polygon" or out.area < 2.0:
        return poly
    if not 0.88 <= out.area / max(poly.area, 1e-9) <= 1.12:
        return poly
    return out


def regularize_facade_footprint(fp: Polygon, support_xy: np.ndarray, cell: float) -> Polygon:
    """Two-stage facade regularisation: scan-supported line fitting + micro-corner removal."""
    g = v63.regularize_facade_footprint(fp, support_xy, cell)
    g2 = _remove_micro_corners(g, cell)
    # A final mild simplify suppresses centimetric waviness but preserves genuine bends.
    q = g2.simplify(max(0.10, 1.35 * cell), preserve_topology=True)
    if q.geom_type == "Polygon" and q.area >= 0.94 * g2.area:
        g2 = q
    return g2


def _regularize_interior_walls(walls: list[base.Wall]) -> list[base.Wall]:
    """Snap physical partitions to locally dominant families and reconnect junctions."""
    if not walls:
        return []
    good = [w for w in walls if math.hypot(w.x2-w.x1, w.y2-w.y1) >= 0.75]
    if not good:
        return []
    angles = []
    lengths = []
    for w in good:
        angles.append(_line_angle((w.x1,w.y1),(w.x2,w.y2)))
        lengths.append(math.hypot(w.x2-w.x1, w.y2-w.y1))
    order = np.argsort(-np.asarray(lengths))
    groups: list[list[int]] = []
    centres: list[float] = []
    for idx in order:
        a = angles[int(idx)]
        hit = None
        for gi,c in enumerate(centres):
            if v63._adiff(a,c) <= 7.0:
                hit = gi; break
        if hit is None:
            groups.append([int(idx)]); centres.append(a)
        else:
            groups[hit].append(int(idx))
            centres[hit] = v63._mean_angle180([angles[k] for k in groups[hit]], [lengths[k] for k in groups[hit]])
    for w in good:
        a = _line_angle((w.x1,w.y1),(w.x2,w.y2))
        fam = min(centres, key=lambda c: v63._adiff(a,c))
        if v63._adiff(a,fam) > 7.0:
            continue
        p1 = np.array([w.x1,w.y1],dtype=float); p2=np.array([w.x2,w.y2],dtype=float)
        mid=.5*(p1+p2); L=float(np.linalg.norm(p2-p1)); r=math.radians(fam); u=np.array([math.cos(r),math.sin(r)])
        a1=mid-.5*L*u; a2=mid+.5*L*u
        w.x1,w.y1=map(float,a1); w.x2,w.y2=map(float,a2)
        w.theta_deg=float((fam+90.0)%180.0)
    good = core.merge_collinear(good, 0.85)
    good = core.deduplicate_physical_walls(good)
    good = snap_wall_graph(good, 0.62)
    for i,w in enumerate(good,1): w.id=i
    return good


def spaces_from_wall_solids(footprint: Polygon, walls: list[base.Wall], storey: base.Storey) -> list[base.Space]:
    """Recover rooms as free-space cells after subtracting validated partition solids."""
    ext = [w for w in walls if str(w.source).startswith("closed_facade_envelope")]
    th = float(np.median([w.thickness for w in ext])) if ext else 0.34
    inner = footprint.buffer(-max(0.10,0.52*th), join_style=2)
    if inner.geom_type == "MultiPolygon": inner=max(inner.geoms,key=lambda p:p.area)
    if inner.geom_type != "Polygon" or inner.area < 2.0:
        return []
    solids=[]
    for w in walls:
        if str(w.source).startswith("closed_facade_envelope"):
            continue
        L=math.hypot(w.x2-w.x1,w.y2-w.y1)
        if L < 0.95 or w.confidence < 0.52:
            continue
        if getattr(w,"geometric_feedback",0.0) < 0.10 and w.confidence < 0.74:
            continue
        ln=v63._extend_line(LineString([(w.x1,w.y1),(w.x2,w.y2)]),0.68).intersection(inner)
        geoms=[ln] if ln.geom_type=="LineString" else list(getattr(ln,"geoms",[]))
        for q in geoms:
            if q.length >= 0.85:
                solids.append(q.buffer(max(0.06,0.50*w.thickness),cap_style=2,join_style=2))
    free=inner if not solids else inner.difference(unary_union(solids))
    polys=[free] if free.geom_type=="Polygon" else list(getattr(free,"geoms",[]))
    polys=[p for p in polys if p.geom_type=="Polygon" and p.area>=2.0]
    cleaned=[]
    for p in polys:
        r=p.minimum_rotated_rectangle; rc=np.asarray(r.exterior.coords,dtype=float)
        sides=[float(np.linalg.norm(rc[i+1]-rc[i])) for i in range(4)] if len(rc)>=5 else [0]
        compact=float(4*math.pi*p.area/max(p.length*p.length,1e-9))
        if min(sides,default=0)<0.70 or compact<0.035:
            continue
        cleaned.append(p)
    if not cleaned:
        cleaned=[inner]
    cleaned=sorted(cleaned,key=lambda p:p.area,reverse=True)[:int(np.clip(round(inner.area/5.0),1,18))]
    out=[]
    for i,p in enumerate(cleaned,1):
        closure=float(np.clip(p.area/max(p.convex_hull.area,1e-9),0,1))
        conf=float(np.clip(.60+.24*closure+.16*min(1,p.area/10.0),0,.97))
        out.append(base.Space(i,storey.id,f"Room_{i:02d}",[[float(x),float(y)] for x,y in list(p.exterior.coords)[:-1]],storey.z0,storey.z1,float(p.area),conf))
    return out


def _plane_from_vertices(vertices):
    a=np.asarray(vertices,dtype=float)
    A=np.column_stack((a[:,0],a[:,1],np.ones(len(a))))
    abc,*_=np.linalg.lstsq(A,a[:,2],rcond=None)
    return abc


def _regular_roof_poly(poly: Polygon, envelope: Polygon, cell: float) -> Polygon | None:
    if poly.geom_type!="Polygon" or poly.area<0.7:
        return None
    g=poly.simplify(max(.10,.85*cell),preserve_topology=True)
    if g.geom_type!="Polygon": g=poly
    rect=g.minimum_rotated_rectangle
    if rect.geom_type=="Polygon":
        fill=g.area/max(rect.area,1e-9)
        if fill>=.72 and rect.area<=1.24*g.area:
            q=rect.intersection(envelope)
            if q.geom_type=="Polygon" and q.area>=.92*g.area:
                g=q
    # If not rectangular, progressively remove centimetric roof-edge serrations.
    area0=g.area; best=g; tol=max(.12,1.05*cell)
    for _ in range(7):
        q=g.simplify(tol,preserve_topology=True)
        if q.geom_type!="Polygon" or q.area<.90*area0: break
        best=q
        if len(q.exterior.coords)-1<=6: break
        tol*=1.20
    return best


def regularize_roof_facets(facets: list[RoofFacet], footprint: Polygon, raster: float) -> list[RoofFacet]:
    """Merge coplanar adjacent patches and replace zig-zag boundaries with architectural facets."""
    if not facets:
        return []
    cell=float(np.clip(max(.12,2.4*raster),.12,.20)); envelope=footprint.buffer(3.0)
    items=[]
    for f in facets:
        poly=Polygon([(v[0],v[1]) for v in f.vertices])
        if not poly.is_valid: poly=poly.buffer(0)
        if poly.geom_type!="Polygon" or poly.area<.7: continue
        abc=_plane_from_vertices(f.vertices); items.append([f,poly,abc])
    used=set(); out=[]
    for i,(f,p,a) in enumerate(items):
        if i in used: continue
        group=[i]; used.add(i); merged=p; coeff=[a]
        for j,(g,q,b) in enumerate(items):
            if j in used: continue
            slope_diff=float(np.linalg.norm(np.asarray(a[:2])-np.asarray(b[:2])))
            c0=np.array([p.centroid.x,p.centroid.y]); dz=abs(float((a[0]-b[0])*c0[0]+(a[1]-b[1])*c0[1]+a[2]-b[2]))
            if slope_diff<=.075 and dz<=.18 and merged.distance(q)<=.28:
                u=merged.union(q)
                if u.geom_type=="Polygon":
                    merged=u; group.append(j); coeff.append(b); used.add(j)
        poly=_regular_roof_poly(merged,envelope,cell)
        if poly is None: continue
        abc=np.mean(np.asarray(coeff),axis=0)
        verts=[[float(x),float(y),float(abc[0]*x+abc[1]*y+abc[2])] for x,y in list(poly.exterior.coords)[:-1]]
        conf=float(np.clip(max(items[k][0].confidence for k in group)+.02,0,.98))
        out.append(RoofFacet(len(out)+1,f.storey_id,verts,float(np.mean([items[k][0].thickness for k in group])),conf,"architectural_plane_regularized_upper_envelope"))
    return out


def _tread_candidates(pts: np.ndarray, storey: base.Storey, raster: float):
    """Find thin horizontal rectangular components at repeated low elevations."""
    cell=float(np.clip(max(.055,1.35*raster),.055,.085)); dz=.055
    zlo=storey.z0-.30; zhi=min(storey.z1-.15,storey.z0+2.20)
    p=pts[(pts[:,2]>=zlo)&(pts[:,2]<=zhi)]
    if len(p)<200:return []
    k=np.floor((p[:,2]-zlo)/dz).astype(int); out=[]
    for kk in np.unique(k):
        q=p[k==kk]
        if len(q)<35: continue
        o=q[:,:2].min(axis=0); ij=np.unique(np.floor((q[:,:2]-o)/cell).astype(int),axis=0)
        xy=o+(ij+.5)*cell
        for ci in v61._components(xy,max(.12,1.8*cell)):
            if len(ci)<8: continue
            s=xy[ci]; hull=MultiPoint(s.tolist()).convex_hull
            if hull.geom_type!="Polygon": continue
            r=hull.minimum_rotated_rectangle; rc=np.asarray(r.exterior.coords,dtype=float)
            if len(rc)<5: continue
            edges=[rc[i+1]-rc[i] for i in range(4)]; lens=np.array([np.linalg.norm(e) for e in edges]); order=np.argsort(lens)
            short=float(np.median(lens[order[:2]])); long=float(np.median(lens[order[2:]]))
            if not (.14<=short<=.82 and .55<=long<=3.40 and long/short>=1.35): continue
            area=max(long*short,1e-9); density=float(len(ci)*cell*cell/area)
            if density<.28: continue
            e=edges[int(np.argmax(lens))]; ang=float(math.degrees(math.atan2(e[1],e[0]))%180.0)
            c=np.asarray(r.centroid.coords[0],dtype=float); z=float(np.median(q[:,2]))
            out.append({"c":c,"z":z,"width":long,"depth":short,"angle":ang,"density":density})
    # Collapse duplicate detections of the same tread in neighbouring elevation bins.
    keep=[]
    for c in sorted(out,key=lambda x:(x["z"],-x["density"])):
        if any(abs(c["z"]-d["z"])<.075 and np.linalg.norm(c["c"]-d["c"])<.16 for d in keep): continue
        keep.append(c)
    return keep


def detect_stair_flights(pts: np.ndarray, footprint: Polygon, storey: base.Storey, raster: float) -> list[StairFlight]:
    """Detect staircase flights from repeated, parallel, regularly rising tread surfaces."""
    c=_tread_candidates(pts,storey,raster)
    if len(c)<3:return []
    order=sorted(range(len(c)),key=lambda i:c[i]["z"]); dp={i:[i] for i in order}
    for ii,i in enumerate(order):
        for j in order[ii+1:]:
            rise=c[j]["z"]-c[i]["z"]
            if rise>.26: break
            if not .09<=rise<=.24: continue
            if v63._adiff(c[i]["angle"],c[j]["angle"])>12: continue
            if not .60<=c[j]["width"]/max(c[i]["width"],1e-6)<=1.55: continue
            d=c[j]["c"]-c[i]["c"]; dist=float(np.linalg.norm(d))
            if not .10<=dist<=.62: continue
            r=math.radians(c[i]["angle"]); long_axis=np.array([math.cos(r),math.sin(r)])
            if abs(float((d/dist)@long_axis))>.50: continue
            cand=dp[i]+[j]
            if len(cand)>len(dp.get(j,[j])): dp[j]=cand
    paths=sorted(dp.values(),key=len,reverse=True); used=set(); out=[]
    for path in paths:
        path=[i for i in path if i not in used]
        if len(path)<3: continue
        path=sorted(path,key=lambda i:c[i]["z"]); rises=np.diff([c[i]["z"] for i in path]); centres=np.array([c[i]["c"] for i in path])
        d=centres[-1]-centres[0]; L=float(np.linalg.norm(d))
        if L<.25: continue
        run=d/L; steps=np.diff(centres,axis=0)@run
        if np.median(steps)<=.10: continue
        rise=float(np.median(rises)); tread=float(np.median(steps)); width=float(np.median([c[i]["width"] for i in path]))
        rise_cv=float(np.std(rises)/max(rise,1e-6)); tread_cv=float(np.std(steps)/max(tread,1e-6))
        if rise_cv>.35 or tread_cv>.45: continue
        theta=float(math.degrees(math.atan2(run[1],run[0]))%360.0); p0=centres[0]
        # Stairs are allowed just outside the masonry shell (porch/entrance) but not far away.
        if footprint is not None and footprint.distance(Point(float(p0[0]),float(p0[1])))>3.2: continue
        conf=float(np.clip(.48+.08*len(path)+.18*(1-rise_cv)+.14*(1-tread_cv),0,.97))
        out.append(StairFlight(len(out)+1,storey.id,float(p0[0]),float(p0[1]),float(c[path[0]]["z"]-.5*rise),float(np.clip(width,.55,3.4)),float(np.clip(tread,.18,.45)),float(np.clip(rise,.10,.23)),len(path),theta,conf))
        used.update(path)
        if len(out)>=8: break
    return out


def reconstruct_bim(request: dict):
    model=v63.reconstruct_bim(request)
    if model.summary.get("scene_mode")=="indoor_room":
        model.stairs=[]
        model.summary.update({"version":"6.4-architectural-primitives","v64_path":"delegated_indoor_graph","reference_bim_used_at_runtime":False})
        return model

    raw=base.load_xyz(request["input"],int(request.get("max_points",2_000_000)))
    raster=float(np.clip(float(request.get("raster_cell_m",.05)),.04,.10)); pts=base.voxel_subsample(raw,max(.03,min(.055,raster)))
    fp=v61._LAST_FOOTPRINT
    if fp is None or fp.geom_type!="Polygon":
        model.stairs=[]; model.summary["version"]="6.4-architectural-primitives"; return model

    support_xy,_,_,cell=v6._facade_columns(pts,raster); reg=regularize_facade_footprint(fp,support_xy,cell)
    old_ext=[w for w in model.walls if str(w.source).startswith("closed_facade_envelope")]
    th=float(np.median([w.thickness for w in old_ext])) if old_ext else .34
    ext=v6.walls_from_footprint(pts,reg,model.storeys[0],model.candidates,th)
    interiors=_regularize_interior_walls([w for w in model.walls if not str(w.source).startswith("closed_facade_envelope")])
    model.walls=ext+interiors; geometric_feedback(pts,model.walls)
    for i,w in enumerate(model.walls,1):w.id=i
    model.spaces=spaces_from_wall_solids(reg,model.walls,model.storeys[0])
    model.roofs=regularize_roof_facets(v63.fit_roof_facets(pts,reg,model.storeys[0],raster),reg,raster)
    model.stairs=detect_stair_flights(pts,reg,model.storeys[0],raster)
    model.openings=v63.detect_openings(pts,model.walls,raster); v61._dedupe_openings(model)
    for i,o in enumerate(model.openings,1):o.id=i

    s=model.summary; s.update({
        "version":"6.4-architectural-primitives","scene_mode":"exterior_building_shell",
        "wall_reconstruction":"scan_fitted_architectural_line_families_with_microcorner_suppression",
        "space_reconstruction":"validated_wall_solid_subtraction_and_free_space_components",
        "roof_reconstruction":"coplanar_merge_plus_architectural_boundary_regularization",
        "stair_reconstruction":"repeated_horizontal_tread_sequences",
        "footprint_vertices":len(reg.exterior.coords)-1,"walls":len(model.walls),"spaces":len(model.spaces),
        "roof_facets":len(model.roofs),"stairs":len(model.stairs),"doors":sum(o.kind=="Door" for o in model.openings),
        "windows":sum(o.kind=="Window" for o in model.openings),"openings":len(model.openings),"reference_bim_used_at_runtime":False})
    warnings=s.setdefault("warnings",[])
    if not model.stairs: warnings.append("No staircase flight passed the repeated-tread geometry checks")
    if len(model.spaces)<=1: warnings.append("Only one interior free-space cell was reconstructed; partition evidence remains incomplete")
    if not model.roofs: warnings.append("No roof facet passed v6.4 architectural regularisation")
    return model
